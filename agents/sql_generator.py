"""SQL Generator Agent.

Uses the LLM to write one INSERT ... SELECT per target object. It is a prompt
chain: step 1 plans (filters, joins, expressions, skipped rows), step 2 writes
the SQL from that plan with two few-shot examples. On a retry it receives the
Validator's coded feedback and the previous SQL, and repairs only what was
flagged.
"""
from __future__ import annotations

import re
from pathlib import Path

from .base import AgentError, BaseAgent

FEWSHOT_FILE = "sql_generator_fewshot.md"


def _plan_facts(facts: dict) -> dict:
    return {
        "load_order": facts["load_order"],
        "mapping_status": facts["mapping_status"],
        "targets": facts["targets"],
        "required_unmapped": facts["required_unmapped"],
    }


class SQLGeneratorAgent(BaseAgent):
    name = "sql_generator"

    def run(self, state: dict) -> dict:
        attempt = state.get("attempt", 0) + 1
        facts, brief = state["facts"], state["brief"]
        plan = state.get("plan")
        if not plan:
            plan = self.ask("sql_generator_plan", {
                "facts": _plan_facts(facts),
                "brief": brief,
                "memory_hints": state.get("memory_hints", []),
            })
        feedback = state.get("feedback", []) if attempt > 1 else []
        previous = [{"target": s["target"], "sql": s["sql"]} for s in state.get("statements", [])] if attempt > 1 else []
        fewshot = (Path(self.prompts_dir) / FEWSHOT_FILE).read_text(encoding="utf-8")
        reply = self.ask("sql_generator_sql", {
            "plan": plan,
            "facts": _plan_facts(facts),
            "brief": {"load_order": brief["load_order"], "assumptions": brief.get("assumptions", [])},
            "previous_sql": previous,
            "feedback": feedback,
            "fewshot": fewshot,
        })
        statements = self._clean(reply)
        sql_text = self._assemble(statements, brief, attempt)
        msg = self.message("validator", "sql_candidate", {
            "attempt": attempt,
            "statements": [{"target": s["target"], "rationale": s["rationale"]} for s in statements],
            "feedback_applied": [f"{f['code']} {f['target']}" for f in feedback],
        }, attempt)
        return {"plan": plan, "statements": statements, "sql_text": sql_text, "attempt": attempt, "messages": [msg]}

    @staticmethod
    def _clean(reply: dict) -> list[dict]:
        if not isinstance(reply, dict) or not isinstance(reply.get("statements"), list) or not reply["statements"]:
            raise AgentError("sql_generator: the model did not return a 'statements' list")
        out = []
        for s in reply["statements"]:
            sql = re.sub(r";\s*$", "", str(s.get("sql", "")).strip())
            out.append({"target": str(s.get("target", "")).strip(), "sql": sql,
                        "rationale": str(s.get("rationale", "")).strip()})
        return out

    def _assemble(self, statements: list[dict], brief: dict, attempt: int) -> str:
        lines = [
            "-- Migration script: Raiser's Edge -> Salesforce Nonprofit Cloud (dummy data)",
            f"-- Generated by multi_agent_sql_tool, LLM backend: {self.llm.describe()}",
            f"-- Attempt that passed or last attempt: {attempt}",
            f"-- Load order: {' -> '.join(brief['load_order'])}",
        ]
        if self.llm.name == "fake":
            lines.append("-- NOTE: produced by the offline rule-based stub, not a real language model.")
        lines.append("")
        for i, s in enumerate(statements, start=1):
            lines.append(f"-- [{i}] {s['target']}: {s['rationale']}")
            lines.append(s["sql"] + ";")
            lines.append("")
        return "\n".join(lines)
